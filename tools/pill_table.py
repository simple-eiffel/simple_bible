"""Write .eiffel-workflow/gui/03-PILLS.md from the window's design pills.

The pills (View > Show design pills) are declared in gui_app/bib_gui_app.e by
window.add_reference_mark (widget, "CODE", "tip", corner), inside add_chrome_pills
(both boards), add_pills (the Simple board) and add_study_pills (the Study board).
This reads every such call and writes one table, so the document always says what
the running program shows. Run it after any pill changes:  python tools/pill_table.py
"""
import re
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "gui_app" / "bib_gui_app.e"
TARGET = ROOT / ".eiffel-workflow" / "gui" / "03-PILLS.md"

CALL = re.compile(r'add_reference_mark\s*\(\s*([a-z_]+)\s*,\s*"([^"]+)"\s*,\s*(?:\{STRING_32\}\s*)?"((?:[^"%]|%.)*)"')
ROUTINE = re.compile(r"^\t([a-z_]+)\b", re.M)
BOARDS = {"add_chrome_pills": "Both", "add_pills": "Simple", "add_study_pills": "Study"}


def code_key(code):
    """C1 < C2 < C10 < C6.1: letters first, then each number in turn."""
    letters = re.match(r"[A-Z]+", code).group(0)
    numbers = [int(n) for n in re.findall(r"\d+", code)]
    return (letters, numbers)


def main():
    text = SOURCE.read_text(encoding="utf-8")
    starts = [(m.start(), m.group(1)) for m in ROUTINE.finditer(text)]
    rows = {}
    for m in CALL.finditer(text):
        widget, code, tip = m.groups()
        before = [st for st in starts if st[0] < m.start()]
        routine = before[-1][1] if before else "?"
        board = BOARDS.get(routine, routine)
        tip = tip.replace('%"', '"').replace("%%", "%")
        rows.setdefault((code, board), (widget, tip))
    lines = [
        "# 03 PILLS: the window's design pills",
        "",
        "Generated by `tools/pill_table.py` from the `add_reference_mark` calls in",
        "`gui_app/bib_gui_app.e`; do not edit by hand. View > Show design pills (Ctrl+Shift+P)",
        "shows each code on the window part it names, with this tip. Give feedback by code.",
        "",
        "Boards: Simple (the Simple layout), Study (the Study layout), Both (the chrome, on each).",
        "A part can carry a different code on each board.",
        "",
        "| Code | Board | Window part | Tip |",
        "|------|-------|-------------|-----|",
    ]
    for code, board in sorted(rows, key=lambda k: (code_key(k[0]), k[1])):
        widget, tip = rows[(code, board)]
        lines.append("| %s | %s | `%s` | %s |" % (code, board, widget, tip.replace("|", "/")))
    lines.append("")
    TARGET.write_text("\n".join(lines), encoding="utf-8", newline="\r\n")
    print("%d pills written to %s" % (len(rows), TARGET.relative_to(ROOT)))


if __name__ == "__main__":
    main()
